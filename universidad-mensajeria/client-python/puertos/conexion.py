"""Puertos de transporte y callbacks entrantes (sin DTO de protocolo)."""
from __future__ import annotations

from typing import Protocol, runtime_checkable

from puertos.contratos import RespuestaRed


@runtime_checkable
class ReceptorMensajes(Protocol):
    def al_recibir(self, mensaje: RespuestaRed) -> None: ...

    def al_cierre(self, aviso: RespuestaRed) -> None: ...

    def al_error(self, motivo: str) -> None: ...

    def al_desconexion(self) -> None: ...


@runtime_checkable
class IInterfazConexionRed(Protocol):
    def conectar(self) -> None: ...

    def desconectar(self) -> None: ...

    def conectado(self) -> bool: ...

    def suscribir(self, receptor: ReceptorMensajes) -> None: ...

    def login(self, codigo: str, contrasena: str) -> RespuestaRed: ...

    def enviar_texto(self, remitente: str, destinatario: str, contenido: str,
                     id: str | None = None) -> RespuestaRed: ...

    def enviar_imagen(self, remitente: str, destinatario: str, nombre_archivo: str,
                      mime: str, contenido_base64: str, id: str | None = None) -> RespuestaRed: ...

    def enviar_archivo(self, remitente: str, destinatario: str, nombre_archivo: str,
                       mime: str, contenido_base64: str, id: str | None = None) -> RespuestaRed: ...

    def enviar_archivo_fragmentado(self, id: str, remitente: str, destinatario: str,
                                   nombre_archivo: str, mime: str,
                                   contenido: bytes) -> RespuestaRed: ...

    def difundir(self, remitente: str, contenido: str, id: str | None = None) -> RespuestaRed: ...

    def listar_conectados(self) -> RespuestaRed: ...

    def expulsar(self, codigo: str) -> RespuestaRed: ...

    def solicitar_historial(self, remitente: str, destinatario: str,
                            pagina: int) -> RespuestaRed: ...

    def descargar_archivo(self, archivo_id: str) -> RespuestaRed: ...

    def logout(self) -> None: ...

    def enviar_lectura(self, lector: str, autor: str, id_original: str) -> RespuestaRed: ...

    def listar_usuarios(self) -> RespuestaRed: ...
