"""Puerto de historial local por cuenta, blobs y cola de reintento."""
from __future__ import annotations

from typing import Protocol, runtime_checkable

from puertos.datos import MensajeLocal, PendienteEnvio, RecienteChat


@runtime_checkable
class IInterfazHistorialLocal(Protocol):
    def preparar_cuenta(self, codigo: str) -> None: ...

    def guardar(self, mensaje: MensajeLocal) -> None: ...

    def pagina(self, remitente: str, destinatario: str,
               limite: int, offset: int) -> list[MensajeLocal]: ...

    def contar(self, remitente: str, destinatario: str) -> int: ...

    def buscar(self, remitente: str, destinatario: str,
               patron: str, limite: int) -> list[MensajeLocal]: ...

    def marcar_descargado(self, id_mensaje: str, ruta_archivo: str) -> None: ...

    def marcar_estado(self, id_mensaje: str, estado: str) -> None: ...

    def marcar_leidos_de(self, yo: str, otro: str) -> None: ...

    def ids_no_leidos(self, yo: str, otro: str) -> list[str]: ...

    def recientes(self, yo: str) -> list[RecienteChat]: ...

    def blob_por_id(self, id_mensaje: str) -> str | None: ...

    def archivo_id_por_id(self, id_mensaje: str) -> str | None: ...

    def actualizar_archivo_id(self, id_mensaje: str, archivo_id: str) -> None: ...

    def actualizar_etapas_filtrado(self, id_mensaje: str,
                                   etapas_filtrado: str) -> None: ...

    def actualizar_contenido(self, id_mensaje: str, base64: str) -> None: ...

    def pendientes(self) -> list[PendienteEnvio]: ...

    def registrar_pendiente(self, pendiente: PendienteEnvio) -> None: ...

    def incrementar_intento(self, id: str, ultimo_error: str) -> None: ...

    def eliminar_pendiente(self, id: str) -> None: ...

    def pendiente_por_id(self, id: str) -> PendienteEnvio | None: ...
